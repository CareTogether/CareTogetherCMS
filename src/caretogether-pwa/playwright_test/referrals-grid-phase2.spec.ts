function row(
  id: string,
  overrides: Partial<ReferralBrowserRowV2> = {}
): ReferralBrowserRowV2 {
  return {
    id,
    referralCount: 1,
    title: 'Referral',
    status: 'OPEN',
    openedAtUtc: new Date('2026-01-01'),
    acceptedAtUtc: null,
    closedAtUtc: null,
    clientFamilyName: 'Same family',
    county: 'North',
    comments: '',
    searchableText: 'Referral',
    assignmentPersonIdsByRole: {},
    assignmentNamesByRole: {},
    customFieldValues: {},
    ...overrides,
  };
}

const field = (name: string, type: CustomFieldType, validValues?: string[]) =>
  new CustomField({ name, type, validValues });
const columns = (rows: ReferralBrowserRowV2[], fields: CustomField[] = []) =>
  buildReferralsColumns(rows, [], fields, ['North', 'South'], false);

function pivot(
  rows: ReferralBrowserRowV2[],
  definitions: GridColDef<ReferralBrowserRowV2>[],
  dimension = 'status',
  columnDimension?: string
) {
  const apiRef = {
    current: {
      state: { pivoting: { active: true } },
      getRowValue: (
        record: ReferralBrowserRowV2,
        column: GridColDef<ReferralBrowserRowV2>
      ): unknown =>
        column.valueGetter
          ? column.valueGetter(undefined as never, record, column, apiRef)
          : record[column.field as keyof ReferralBrowserRowV2],
      getRowFormattedValue: (
        record: ReferralBrowserRowV2,
        column: GridColDef<ReferralBrowserRowV2>
      ): unknown => {
        const value = apiRef.current.getRowValue(record, column);
        return column.valueFormatter
          ? column.valueFormatter(value as never, record, column, apiRef)
          : value;
      },
    } as unknown as GridApiPremium,
  };
  return createPivotPropsFromRows({
    rows,
    columns: getInitialColumns(
      definitions,
      undefined,
      (() => '') as GridApiPremium['getLocaleText']
    ),
    pivotModel: {
      rows: [{ field: dimension }],
      columns: columnDimension ? [{ field: columnDimension }] : [],
      values: [{ field: 'referralCount', aggFunc: 'sum' }],
    },
    apiRef,
  });
}

test('derives reporting eligibility for three configurations and newly added fields', () => {
  const configA = [
    field('Program', CustomFieldType.String, ['A', 'B']),
    field('Stable', CustomFieldType.Boolean),
    field('Notes', CustomFieldType.String),
    field('Needs', CustomFieldType.StringArray),
  ];
  const a = columns(
    [
      row('1', {
        customFieldValues: {
          Program: 'A',
          Stable: false,
          Notes: 'private',
          Needs: ['Food'],
        },
      }),
    ],
    configA
  );
  const b = columns(
    [row('1', { customFieldValues: { Region: 'East' } })],
    [field('Region', CustomFieldType.String, ['East'])]
  );
  const c = columns([row('1')]);
  for (const name of ['Program', 'Stable']) {
    expect(
      a.find((column) => column.field === `referralCustomField:${name}`)
    ).toMatchObject({ pivotable: true, chartable: true });
  }
  for (const name of ['Notes', 'Needs']) {
    expect(
      a.find((column) => column.field === `referralCustomField:${name}`)
    ).toMatchObject({ pivotable: false, chartable: false });
  }
  expect(b.find((column) => column.field.endsWith(':Region'))).toMatchObject({
    pivotable: true,
    chartable: true,
  });
  expect(b.some((column) => column.field.endsWith(':Program'))).toBe(false);
  expect(
    c.some((column) => column.field.startsWith('referralCustomField:'))
  ).toBe(false);
  const added = columns(
    [row('1', { customFieldValues: { New: true } })],
    [field('New', CustomFieldType.Boolean)]
  );
  expect(added.find((column) => column.field.endsWith(':New'))).toMatchObject({
    pivotable: true,
    chartable: true,
  });
});

