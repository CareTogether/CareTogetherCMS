  const built = columns(
    [record],
    [field('Added', CustomFieldType.String, ['Option'])]
  );
  const added = built.find((column) => column.field.endsWith(':Added'))!;
  expect(added).toMatchObject({
    pivotable: true,
    chartable: true,
    type: 'singleSelect',
  });
  const apiRef = { current: undefined as unknown as GridApiPremium };
  const predicate = added
    .filterOperators!.find((operator) => operator.value === 'is')!
    .getApplyFilterFn(
      { field: added.field, operator: 'is', value: 'Option' },
      added
    )!;
  expect(predicate('Option', record, added, apiRef)).toBe(true);
  expect(added.valueFormatter!('Option' as never, record, added, apiRef)).toBe(
    'Option'
  );
  expect(pivot([record], built, added.field, 'status').rows).toHaveLength(1);
