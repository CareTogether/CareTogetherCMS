test('native Pivot preserves referral identity, missing dimensions and exact numeric counts', () => {
  const rows = [
    row('1'),
    row('2', { status: 'ACCEPTED' }),
    row('3', { clientFamilyName: null, county: null }),
  ];
  const original = structuredClone(rows);
  const result = pivot(rows, columns(rows), 'county', 'status');
  expect(result.rows.map((record) => record.id)).toEqual(['1', '2', '3']);
  const measures = Object.keys(result.aggregationModel!);
  const total = measures.reduce(
    (sum, measure) =>
      sum +
      GRID_AGGREGATION_FUNCTIONS.sum.apply({
        values: result.rows.map((record) => record[measure]),
        field: measure,
      }),
    0
  );
  expect(total).toBe(3);
  expect(rows).toEqual(original);
  expect(result.columnGroupingModel?.map((group) => group.headerName)).toEqual([
    'Open',
    'Accepted',
  ]);
  expect(isOptionalReferralsColumn('referralCount')).toBe(true);
});

test('native quick-filter and status predicates feed the same Pivot count measure', () => {
  const rows = [
    row('1', { searchableText: 'needle' }),
    row('2', { searchableText: 'needle', status: 'CLOSED' }),
    row('3'),
  ];
  const built = columns(rows);
  const search = built.find((column) => column.field === 'searchableText')!;
  const apiRef = { current: undefined as unknown as GridApiPremium };
  const predicate = search.getApplyQuickFilterFn!(' NEEDLE ', search, apiRef)!;
  const matching = rows.filter((record) =>
    predicate(record.searchableText, record, search, apiRef)
  );
  const result = pivot(matching, built);
  expect(
    GRID_AGGREGATION_FUNCTIONS.sum.apply({
      values: result.rows.map((record) => record.referralCount),
      field: 'referralCount',
    })
  ).toBe(2);
  const status = built.find((column) => column.field === 'status')!;
  const filter = status
    .filterOperators!.find((operator) => operator.value === 'is')!
    .getApplyFilterFn(
      { field: 'status', operator: 'is', value: 'OPEN' },
      status
    )!;
  const combined = matching.filter((record) =>
    filter(record.status, record, status, apiRef)
  );
  expect(pivot(combined, built).rows).toHaveLength(1);
  expect(pivot(rows, built).rows).toHaveLength(3);
});

