test('native filtering engine composes search, status, county, assignment and custom fields', () => {
  const rows = [
    row('1', {
      searchableText: 'John full comment',
      customFieldValues: { Flag: true },
      assignmentPersonIdsByRole: { Worker: ['person-1'] },
    }),
    row('2', {
      searchableText: 'John full comment',
      status: 'CLOSED',
      county: 'South',
      customFieldValues: { Flag: false },
    }),
    row('3', {
      searchableText: 'Other person',
      customFieldValues: { Flag: true },
    }),
  ];
  const built = buildReferralsColumns(
    rows,
    [{ role: 'Worker', options: [{ value: 'person-1', label: 'Jane' }] }],
    [field('Flag', CustomFieldType.Boolean)],
    ['North', 'South'],
    false
  );
  const lookup = Object.fromEntries(
    getInitialColumns(
      built,
      undefined,
      (() => '') as GridApiPremium['getLocaleText']
    )
  );
  const apiRef = {
    current: {
      state: {
        columns: {
          lookup,
          orderedFields: Object.keys(lookup),
          columnVisibilityModel: { searchableText: false },
        },
      },
      rootProps: { ignoreDiacritics: false },
      getColumn: (field: string) => lookup[field],
    },
  } as unknown as Parameters<typeof buildAggregatedFilterApplier>[2];
  const getValue: Parameters<typeof buildAggregatedFilterApplier>[1] = (
    record,
    column
  ) =>
    column.valueGetter
      ? column.valueGetter(undefined as never, record, column, apiRef)
      : record[column.field];
  const items = [
    { id: 1, field: 'status', operator: 'is', value: 'OPEN' },
    { id: 2, field: 'county', operator: 'isAnyOf', value: ['North'] },
    {
      id: 3,
      field: 'assignmentRole:Worker',
      operator: 'contains',
      value: ['person-1'],
    },
    { id: 4, field: 'referralCustomField:Flag', operator: 'is', value: 'true' },
  ];
  const matching = (model: GridFilterModel) => {
    const apply = buildAggregatedFilterApplier(model, getValue, apiRef, true);
    return rows
      .filter((record) => {
        const result = {} as Parameters<typeof apply>[2];
        apply(record, undefined, result);
        return passFilterLogic(
          [result.passingFilterItems],
          [result.passingQuickFilterValues],
          model,
          getValue,
          apiRef,
          {}
        );
      })
      .map((record) => record.id);
  };
  const model: GridFilterModel = {
    items,
    logicOperator: GridLogicOperator.And,
    quickFilterValues: [' JOHN '],
    quickFilterExcludeHiddenColumns: false,
  };
  expect(matching(model)).toEqual(['1']);
  expect(
    matching({
      ...model,
      items: items.slice(0, 2),
      logicOperator: GridLogicOperator.Or,
    })
  ).toEqual(['1']);
  expect(
    matching({
      ...model,
      items: [
        { id: 1, field: 'status', operator: 'is', value: 'CLOSED' },
        items[1],
      ],
      logicOperator: GridLogicOperator.Or,
    })
  ).toEqual(['1', '2']);
  expect(matching({ items: [] })).toEqual(['1', '2', '3']);
});

test('native sorting preserves equal-date source order and does not mutate rows', () => {
  const rows = [
    row('b'),
    row('a'),
    row('c', { openedAtUtc: new Date('2026-02-01') }),
  ];
  const params = {} as Parameters<typeof gridDateComparator>[2];
  const ascending = [...rows].sort((a, b) =>
    gridDateComparator(a.openedAtUtc, b.openedAtUtc, params, params)
  );
  const descending = [...rows].sort(
    (a, b) => -gridDateComparator(a.openedAtUtc, b.openedAtUtc, params, params)
  );
  expect(ascending.map((record) => record.id)).toEqual(['b', 'a', 'c']);
  expect(descending.map((record) => record.id)).toEqual(['c', 'b', 'a']);
  expect(rows.map((record) => record.id)).toEqual(['b', 'a', 'c']);
  expect(
    gridStringOrNumberComparator('ACCEPTED', 'OPEN', params, params)
  ).toBeLessThan(0);
  expect(
    gridStringOrNumberComparator('Alpha', 'Zulu', params, params)
  ).toBeLessThan(0);
});
