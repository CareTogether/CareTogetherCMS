let bundle: string;
test.use({ storageState: { cookies: [], origins: [] } });

test.beforeAll(async () => {
  const result = await build({
    input: fileURLToPath(
      new URL('./organizations-grid-harness.tsx', import.meta.url)
    ),
    platform: 'browser',
    tsconfig: false,
    transform: {
      jsx: { runtime: 'automatic' },
      define: {
        'process.env.NODE_ENV': JSON.stringify('production'),
        'import.meta.env': JSON.stringify({
          VITE_APP_AUTH_REDIRECT_URI: 'http://localhost:3000/',
        }),
      },
    },
    plugins: [
      {
        name: 'exclude-local',
        resolveId(source) {
          if (source.split(/[\\/]/).some((part) => part.includes('.local')))
            throw new Error('Excluded path');
          return null;
        },
      },
    ],
    output: { format: 'iife' },
    write: false,
  });
  const output = result.output.find((item) => item.type === 'chunk');
  if (!output || output.type !== 'chunk')
    throw new Error('Missing browser bundle');
  bundle = output.code;
});

async function openOrganizationsGridHarnessPage(
  page: import('@playwright/test').Page,
  query = ''
) {
  await page.route('**/organizations-grid-harness*', (route) =>
    route.fulfill({
      contentType: 'text/html',
      body: '<html><body><div id="root"></div></body></html>',
    })
  );
  await page.goto(`/organizations-grid-harness${query}`);
}

async function mountOrganizationsGrid(page: import('@playwright/test').Page) {
  await openOrganizationsGridHarnessPage(page);
  await page.addScriptTag({ content: bundle });
  await expect(page.getByRole('grid')).toBeVisible();
}

test('mouse row activation leaves no cell outline and preserves category badges', async ({
  page,
}) => {
  await mountOrganizationsGrid(page);
  const cell = page.getByRole('gridcell', {
    name: 'Alpha Organization',
    exact: true,
  });
  await cell.click();
  await expect(page).toHaveURL(
    /\/organizations\/organization\/organization-alpha$/
  );
  await expect(cell).toBeFocused();
  await expect(cell).toHaveCSS('outline-style', 'none');
  await expect(
    page.getByRole('row').filter({ has: cell }).locator('.MuiChip-label')
  ).toHaveText(['Housing']);
});

test('keyboard cell navigation retains visible focus and activates the organization', async ({
  page,
}) => {
  await mountOrganizationsGrid(page);
  const cell = page.getByRole('gridcell', {
    name: 'Alpha Organization',
    exact: true,
  });
  await cell.click();
  await page.keyboard.press('ArrowRight');
  const description = page.getByRole('gridcell', {
    name: 'Family support',
    exact: true,
  });
  await expect(description).toBeFocused();
  await expect(description).toHaveCSS('outline-style', 'solid');
  await expect(description).toHaveCSS('outline-width', '2px');
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(
    /\/organizations\/organization\/organization-alpha$/
  );
});

test('cell controls keep their mouse and keyboard behavior and visible focus', async ({
  page,
}) => {
  await openOrganizationsGridHarnessPage(page, '?controls');
  await page.addScriptTag({ content: bundle });
  const row = page
    .getByRole('row')
    .filter({
      has: page.getByRole('gridcell', {
        name: 'Alpha Organization',
        exact: true,
      }),
    });
  const control = row.getByRole('button', {
    name: 'Inspect organization',
    exact: true,
  });
  await control.click();
  const activated = row.getByRole('button', { name: 'Activated', exact: true });
  await expect(activated).toBeVisible();
  await expect(page).toHaveURL(/\/organizations-grid-harness\?controls$/);
  await page.keyboard.press('Tab');
  await page.keyboard.press('Shift+Tab');
  await expect(activated).toBeFocused();
  expect(
    await activated.evaluate((element) => {
      const style = getComputedStyle(element);
      return (
        element.matches(':focus-visible') &&
        style.outlineStyle !== 'none' &&
        parseFloat(style.outlineWidth) > 0
      );
    })
  ).toBe(true);
  await page.keyboard.press('Space');
  await expect(page).toHaveURL(/\/organizations-grid-harness\?controls$/);
});

test('shows the quick filter when its saved value arrives after the grid mounts', async ({
  page,
}) => {
  await openOrganizationsGridHarnessPage(page);
  await page.evaluate(() =>
    window.localStorage.setItem('organizations-grid-quick-filter', 'Beta')
  );
  await page.addScriptTag({ content: bundle });

  const search = page.getByRole('searchbox').first();
  await expect(search).toBeVisible();
  await expect(search).toHaveValue('Beta');
  await expect(
    page.getByRole('gridcell', { name: 'Alpha Organization', exact: true })
  ).toHaveCount(0);
});

function community({
  id,
  name,
  description = '',
  categoryIds = [],
  memberFamilyCount = 0,
  roleAssignmentCount = 0,
}: {
  id: string;
  name: string;
  description?: string;
  categoryIds?: string[];
  memberFamilyCount?: number;
  roleAssignmentCount?: number;
}) {
  return Community.fromJS({
    id,
    name,
    description,
    categoryIds,
    memberFamilies: Array.from(
      { length: memberFamilyCount },
      (_, index) => `${index}`
    ),
    communityRoleAssignments: Array.from(
      { length: roleAssignmentCount },
      (_, index) => ({ personId: `${index}`, roleId: `role-${index}` })
    ),
  });
}

test('builds one operational-grid row per community with safe category labels and numeric counts', () => {
  const housing = OrganizationCategory.fromJS({
    id: 'housing',
    name: 'Housing',
  });
  const advocacy = OrganizationCategory.fromJS({
    id: 'advocacy',
    name: 'advocacy',
  });
  const rows = buildOrganizationGridRows(
    [
      community({
        id: 'organization-b',
        name: 'Beta Organization',
        description: 'Second organization',
        categoryIds: ['housing', 'missing', 'advocacy'],
        memberFamilyCount: 2,
        roleAssignmentCount: 3,
      }),
      community({ id: 'organization-a', name: 'Alpha Organization' }),
    ],
    new Map([
      [housing.id, housing],
      [advocacy.id, advocacy],
    ])
  );

  expect(rows).toEqual([
    {
      id: 'organization-b',
      name: 'Beta Organization',
      description: 'Second organization',
      categoryLabels: ['advocacy', 'Housing'],
      memberFamilyCount: 2,
      organizationCount: 1,
      roleAssignmentCount: 3,
    },
    {
      id: 'organization-a',
      name: 'Alpha Organization',
      description: '',
      categoryLabels: [],
      memberFamilyCount: 0,
      organizationCount: 1,
      roleAssignmentCount: 0,
    },
  ]);
  expect(organizationGridInitialSortModel).toEqual([
    { field: 'name', sort: 'asc' },
  ]);
});

test('exposes Pivot and Charts reporting measures without changing operational exports', () => {
  const columns = buildOrganizationsGridColumns({
    organizationCategoriesEnabled: true,
  });
  const withoutCategories = buildOrganizationsGridColumns({
    organizationCategoriesEnabled: false,
  });
  const memberFamiliesColumn = columns.find(
    (column) => column.field === 'memberFamilyCount'
  );
  const roleAssignmentsColumn = columns.find(
    (column) => column.field === 'roleAssignmentCount'
  );
  const organizationCountColumn = columns.find(
    (column) => column.field === 'organizationCount'
  );
  const nameColumn = columns.find((column) => column.field === 'name');
  const descriptionColumn = columns.find(
    (column) => column.field === 'description'
  );
  const categoriesColumn = columns.find(
    (column) => column.field === 'categoryLabels'
  );

  expect(columns.map((column) => column.field)).toEqual([
    'name',
    'description',
    'categoryLabels',
    'memberFamilyCount',
    'roleAssignmentCount',
    'organizationCount',
  ]);
  expect(withoutCategories.map((column) => column.field)).not.toContain(
    'categoryLabels'
  );
  expect(categoryLabelsForDisplay(['Housing', 'Advocacy'])).toBe(
    'Housing, Advocacy'
  );
  expect(memberFamiliesColumn?.type).toBe('number');
  expect(roleAssignmentsColumn?.type).toBe('number');
  expect(organizationCountColumn).toMatchObject({
    aggregable: true,
    availableAggregationFunctions: ['sum'],
    chartable: true,
    disableExport: true,
    pivotable: false,
  });
  expect(organizationCountColumn?.getApplyQuickFilterFn).toBeDefined();
  expect(nameColumn).toMatchObject({
    aggregable: false,
    chartable: true,
    pivotable: true,
  });
  expect(descriptionColumn).toMatchObject({
    aggregable: false,
    chartable: false,
    groupable: false,
    pivotable: false,
  });
  expect(categoriesColumn).toMatchObject({
    aggregable: false,
    chartable: false,
    groupable: false,
    pivotable: false,
  });
  [memberFamiliesColumn, roleAssignmentsColumn].forEach((column) =>
    expect(column).toMatchObject({
      aggregable: true,
      availableAggregationFunctions: ['sum'],
      chartable: true,
      pivotable: false,
    })
  );
  expect(organizationGridExportFields).toEqual([
    'name',
    'description',
    'categoryLabels',
    'memberFamilyCount',
    'roleAssignmentCount',
  ]);
  expect(organizationGridFeatureProps).toEqual({
    disableAggregation: true,
    disableRowGrouping: true,
    disableRowSelectionOnClick: true,
  });
});

test('keeps generated Pivot rows out of organization navigation and category access', () => {
  const generatedRow = {
    [GRID_ID_AUTOGENERATED]: 'generated-organization-row',
    id: 'generated-organization-row',
    name: '',
    description: '',
    categoryLabels: [],
    memberFamilyCount: 0,
    organizationCount: 0,
    roleAssignmentCount: 0,
  };
  expect(canNavigateOrganizationRow(generatedRow, false)).toBe(false);
  expect(canNavigateOrganizationRow(generatedRow, true)).toBe(false);
  expect(categoryLabelsForGrid(generatedRow)).toBeNull();
});

test('uses native Quick Filter and opens organizations through mouse and keyboard activation', async ({
  page,
}) => {
  await mountOrganizationsGrid(page);

  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByRole('searchbox').first().fill('Beta Organization');
  await expect(
    page.getByRole('gridcell', { name: 'Alpha Organization', exact: true })
  ).toHaveCount(0);
  await expect(
    page.getByRole('gridcell', { name: 'Beta Organization', exact: true })
  ).toBeVisible();

  await page.getByRole('searchbox').first().fill('');
  await page
    .getByRole('gridcell', { name: 'Beta Organization', exact: true })
    .click();
  await expect(page).toHaveURL(
    /organizations\/organization\/organization-beta$/
  );

  await mountOrganizationsGrid(page);
  const alphaNameCell = page.getByRole('gridcell', {
    name: 'Alpha Organization',
    exact: true,
  });
  await alphaNameCell.focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(
    /organizations\/organization\/organization-alpha$/
  );
});
